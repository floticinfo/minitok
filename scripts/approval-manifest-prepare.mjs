import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { evaluateCommercialReadiness, readApprovalManifest } from "./commercial-readiness.mjs";

/**
 * Prepare an approval manifest for the commercial release gate.
 *
 * This fills every value the repository can prove by itself — package versions,
 * the CLI tarball hash recorded in release-manifest.json, and the VSIX hash — and
 * leaves every owner decision as an unresolved value. The result is deliberately
 * not a valid manifest: the validator rejects it until a named owner records the
 * decisions, so this helper can never be mistaken for an approval.
 */

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sha256 = file => createHash("sha256").update(fs.readFileSync(file)).digest("hex");
const readJson = file => JSON.parse(fs.readFileSync(path.join(root, file), "utf8"));
const pending = "PENDING";

function vsixEvidence(extensionPackage) {
  const relative = path.join("extension", "artifacts", `minitok-extension-${extensionPackage.version}.vsix`);
  const absolute = path.join(root, relative);
  if (!fs.existsSync(absolute)) return { version: pending, sha256: pending, note: `run "npm run package:extension" first; expected ${relative.replace(/\\/g, "/")}` };
  return { version: extensionPackage.version, sha256: sha256(absolute), note: null };
}

const outIndex = process.argv.indexOf("--out");
const outPath = outIndex >= 0 ? process.argv[outIndex + 1] : null;
if (!outPath) {
  console.error("usage: node scripts/approval-manifest-prepare.mjs --out <path outside the repository>");
  process.exit(2);
}

const packageJson = readJson("package.json");
const extensionPackage = readJson("extension/package.json");
const releaseManifest = readJson("release-manifest.json");
const release = releaseManifest.release || {};
if (release.version !== packageJson.version || !release.artifact?.sha256) {
  console.error(`release-manifest.json describes ${release.version || "no release"}; run "npm run release:manifest:generate" on the tagged release commit first.`);
  process.exit(1);
}

const vsix = vsixEvidence(extensionPackage);

const approvals = {
  "legal-owner-approval": { status: pending, owner: "TODO legal owner", decision: "TBD", approvedAt: pending, evidenceRef: { type: "external", reference: "REPLACE_ME" } },
  "privacy-owner-approval": { status: pending, owner: "TODO privacy owner", decision: "TBD", approvedAt: pending, evidenceRef: { type: "external", reference: "REPLACE_ME" } },
  "support-commitments": { status: pending, owner: "TODO support owner", decision: "TBD", approvedAt: pending, evidenceRef: { type: "external", reference: "REPLACE_ME" }, support: { contactOwner: "TODO", sla: "TODO", escalationOwner: "TODO" } },
  "npm-publication-authorization": { status: pending, owner: "TODO publication owner", decision: "TBD", approvedAt: pending, evidenceRef: { type: "external", reference: "REPLACE_ME" }, npmPublication: { package: packageJson.name, version: packageJson.version, registry: "https://registry.npmjs.org/" } },
  "marketplace-publisher-authorization": { status: pending, owner: "TODO publisher owner", decision: "TBD", approvedAt: pending, evidenceRef: { type: "external", reference: "REPLACE_ME" }, marketplacePublication: { publisher: extensionPackage.publisher, extension: extensionPackage.name, version: extensionPackage.version } },
  "registry-publication-verification": { status: pending, owner: "TODO publication owner", decision: "TBD", approvedAt: pending, evidenceRef: { type: "external", reference: "REPLACE_ME" } },
  "production-operations": { status: pending, owner: "TODO operations owner", decision: "TBD", approvedAt: pending, evidenceRef: { type: "external", reference: "REPLACE_ME" }, productionOperations: { deploymentOwner: "TODO", databaseOwner: "TODO", rollbackOwner: "TODO", monitoringOwner: "TODO", signerOwner: "TODO" } },
};

const manifest = {
  _howTo: [
    "Generated by scripts/approval-manifest-prepare.mjs: every machine value is filled in.",
    "This is not an approval. Replace each unresolved value with the named owner",
    "decision and an evidence reference, then verify with:",
    `  MINITOK_COMMERCIAL_APPROVAL_MANIFEST=${outPath} npm run release:verify`,
    "Unresolved values are rejected on purpose.",
  ],
  schemaVersion: 2,
  release: {
    package: packageJson.name,
    version: packageJson.version,
    artifacts: {
      cli: { version: packageJson.version, sha256: release.artifact.sha256 },
      vsix: { version: vsix.version, sha256: vsix.sha256 },
    },
  },
  approvals,
};

const absoluteOut = path.resolve(outPath);
fs.mkdirSync(path.dirname(absoluteOut), { recursive: true });
fs.writeFileSync(absoluteOut, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");

const parsed = readApprovalManifest(absoluteOut);
const failClosed = parsed.state !== "VALID";
console.log(JSON.stringify({
  status: "prepared",
  output: absoluteOut,
  release: { package: packageJson.name, version: packageJson.version, cliSha256: release.artifact.sha256, vsixVersion: vsix.version, vsixSha256: vsix.sha256 },
  vsixNote: vsix.note,
  nextSteps: [
    "Record every owner decision in the generated file (status APPROVED, owner, decision, approvedAt, evidenceRef).",
    "Resolve the review notes listed below in the owning document, where the gate reports them.",
    `Verify with: MINITOK_COMMERCIAL_APPROVAL_MANIFEST=${absoluteOut} npm run release:verify`,
  ],
  unresolved: evaluateCommercialReadiness().filter(item => item.status !== "PASS").map(item => ({ id: item.id, status: item.status, markers: item.markers })),
  notAnApproval: failClosed ? "confirmed: unresolved decisions are rejected" : "ERROR: the generated file validated as an approval",
}, null, 2));
if (!failClosed) process.exit(1);

